#!/usr/bin/env python3
"""Generate the public matrix from one explicit, version-aware catalogue."""
from pathlib import Path
import argparse
import json
import sys

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'capabilities.json'
OUTPUT=ROOT/'docs/capabilities/matrix.md'

def generate(source):
    d=json.loads(source.read_text(encoding='utf-8'))
    cols=d['columns']; known=set(d['status_definitions'])
    if len({c['key'] for c in cols})!=len(cols): raise ValueError('duplicate column')
    items=[]
    lines=['<!-- Generated by scripts/generate-capabilities.py: edit capabilities.json, not this table. -->',
    '# Feature and platform availability','',
    f'**Baseline: {d["baseline_date"]}.** This is a published-API inventory, not a certificate of independent native test coverage on every OS. See [limitations](limitations.md).','',
    '## Available runtimes','', '| Entry point | Linux | Windows | Runtime |', '|---|---|---|---|']
    for row in d['platforms']:
        lines.append('| '+' | '.join(row[k].replace('|','\\|') for k in ('entry','linux','windows','edition'))+' |')
    lines.extend(['','## Feature exposure','', '| Capability | '+' | '.join(c['label'] for c in cols)+' | Notes |', '|---|'+'---|'*len(cols)+'---|'])
    symbol={'released':'Released','preview':'Preview','sdk':'Via SDK','not':'—'}
    for feat in d['features']:
        keys=set(feat['cells'])
        if keys != {x['key'] for x in cols}: raise ValueError('mismatched entrypoint cells: '+feat['name'])
        if not set(feat['cells'].values()) <= known: raise ValueError('invalid status: '+feat['name'])
        label=[feat['name']]+[symbol[feat['cells'][c['key']]] for c in cols]+[feat['notes']]
        lines.append('| '+' | '.join(x.replace('|','\\|') for x in label)+' |')
    lines += ['', '## Reading this table','']
    for key,meaning in d['status_definitions'].items():lines.append(f'- **{symbol[key]}** — {meaning}.')
    lines += ['', '## Released package baseline','']
    for col in cols:lines.append(f'- **{col["label"]}:** {d["releases"][col["key"]]}')
    lines += ['', '**Evidence:** [Core](https://github.com/nativehtmlkit/nativehtmlkit-core), [CLI](https://github.com/nativehtmlkit/nativehtmlkit-cli), [Python](https://github.com/nativehtmlkit/nativehtmlkit-python), [PowerShell](https://github.com/nativehtmlkit/nativehtmlkit-powershell), [UI](https://github.com/nativehtmlkit/nativehtmlkit_ui).',
    '', 'The source is a public release inventory. It is not automatically promoted to verified from an agent statement or a code commit. Update the entrypoint version and evidence only following a qualified published release.','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    expected=generate(SOURCE)
    if a.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8')!=expected:
            print('Capability matrix stale; run scripts/generate-capabilities.py',file=sys.stderr);sys.exit(1)
        print('Capability matrix is current')
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True);OUTPUT.write_text(expected,encoding='utf-8');print('Updated',OUTPUT)
if __name__=='__main__':main()
